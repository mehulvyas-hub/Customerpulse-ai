CREATE OR REPLACE TABLE CUSTOMERPULSE_DB.APP.CALL_ANALYSIS AS

SELECT
    CALL_ID,
    CUSTOMER_ID,
    CALL_DATE,
    AGENT_NAME,
    TRANSCRIPT,

    AI_SENTIMENT(TRANSCRIPT) AS SENTIMENT_JSON,

    AI_SENTIMENT(TRANSCRIPT)
        :categories[0]:sentiment::VARCHAR
        AS SENTIMENT

FROM CUSTOMERPULSE_DB.APP.CALL_TRANSCRIPTS;

SELECT *
FROM CUSTOMERPULSE_DB.APP.CALL_ANALYSIS;

SELECT
    CUSTOMER_ID,
    SENTIMENT,
    TRANSCRIPT
FROM CUSTOMERPULSE_DB.APP.CALL_ANALYSIS
WHERE CUSTOMER_ID = 'C1003';